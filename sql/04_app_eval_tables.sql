USE ROLE CIQ_ADMIN;
USE DATABASE CASHLESSIQ;

CREATE TABLE IF NOT EXISTS APP.DECISION (
  DECISION_ID VARCHAR(40) NOT NULL PRIMARY KEY,
  REQUEST_ID VARCHAR(20) NOT NULL REFERENCES DOCS.PREAUTH_REQUEST(REQUEST_ID),
  AGENT_RUN_ID VARCHAR(200),
  MODEL VARCHAR(100),
  OUTCOME VARCHAR(40) NOT NULL CHECK (OUTCOME IN (
    'APPROVE', 'APPROVE_WITH_DEDUCTIONS', 'QUERY', 'REFER'
  )),
  PAYABLE_INR NUMBER(12,0) NOT NULL,
  DECISION_JSON VARIANT NOT NULL,
  SCHEMA_VALID BOOLEAN NOT NULL,
  LATENCY_MS NUMBER(12,0) NOT NULL,
  CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS APP.REVIEW_ACTION (
  ACTION_ID VARCHAR(40) NOT NULL PRIMARY KEY,
  DECISION_ID VARCHAR(40) NOT NULL REFERENCES APP.DECISION(DECISION_ID),
  REVIEWER VARCHAR(200) NOT NULL,
  ROLE VARCHAR(100) NOT NULL,
  ACTION VARCHAR(20) NOT NULL CHECK (ACTION IN ('ACCEPT', 'EDIT', 'QUERY', 'REFER')),
  FINAL_PAYABLE_INR NUMBER(12,0),
  COMMENT VARCHAR,
  ACTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS APP.SLA_EVENT (
  REQUEST_ID VARCHAR(20) NOT NULL REFERENCES DOCS.PREAUTH_REQUEST(REQUEST_ID),
  EVENT VARCHAR(30) NOT NULL CHECK (EVENT IN (
    'RECEIVED', 'DRAFTED', 'DECIDED', 'BREACH_WARNING'
  )),
  AT TIMESTAMP_TZ NOT NULL,
  PRIMARY KEY (REQUEST_ID, EVENT, AT)
);

CREATE TABLE IF NOT EXISTS EVAL.GOLDEN_CASE (
  REQUEST_ID VARCHAR(20) NOT NULL PRIMARY KEY REFERENCES DOCS.PREAUTH_REQUEST(REQUEST_ID),
  EXPECTED_OUTCOME VARCHAR(40) NOT NULL CHECK (EXPECTED_OUTCOME IN (
    'APPROVE', 'APPROVE_WITH_DEDUCTIONS', 'QUERY', 'REFER'
  )),
  EXPECTED_PAYABLE_INR NUMBER(12,0),
  TOLERANCE_INR NUMBER(12,0) NOT NULL DEFAULT 0,
  EXPECTED_CLAUSE_IDS ARRAY NOT NULL,
  TAGS ARRAY NOT NULL
);

CREATE TABLE IF NOT EXISTS EVAL.EVAL_RUN (
  EVAL_RUN_ID VARCHAR(40) NOT NULL PRIMARY KEY,
  MODEL VARCHAR(100) NOT NULL,
  GIT_SHA VARCHAR(40) NOT NULL,
  STARTED_AT TIMESTAMP_TZ NOT NULL,
  COMPLETED_AT TIMESTAMP_TZ
);

CREATE TABLE IF NOT EXISTS EVAL.EVAL_RESULT (
  EVAL_RUN_ID VARCHAR(40) NOT NULL REFERENCES EVAL.EVAL_RUN(EVAL_RUN_ID),
  REQUEST_ID VARCHAR(20) NOT NULL REFERENCES EVAL.GOLDEN_CASE(REQUEST_ID),
  ACTUAL_OUTCOME VARCHAR(40),
  ACTUAL_PAYABLE_INR NUMBER(12,0),
  OUTCOME_MATCH BOOLEAN NOT NULL,
  AMOUNT_MATCH BOOLEAN NOT NULL,
  CITATION_RECALL FLOAT NOT NULL,
  SCHEMA_VALID BOOLEAN NOT NULL,
  LATENCY_MS NUMBER(12,0) NOT NULL,
  ERROR VARCHAR,
  PRIMARY KEY (EVAL_RUN_ID, REQUEST_ID)
);

GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA APP TO ROLE CIQ_APP_USER;
GRANT SELECT ON ALL TABLES IN SCHEMA EVAL TO ROLE CIQ_APP_USER;

