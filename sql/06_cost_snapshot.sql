-- Read-only cost baseline. Run explicitly; never part of make setup or CI.
-- ACCOUNTADMIN is used only to inspect account-wide metering and object state.
-- No AI calls, indexing, extraction, or application startup is performed.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE CIQ_WH;
ALTER SESSION SET STATEMENT_TIMEOUT_IN_SECONDS = 30;
ALTER SESSION SET TIMEZONE = 'UTC';

SHOW WAREHOUSES;
SHOW RESOURCE MONITORS;
SHOW COMPUTE POOLS;
SHOW CORTEX SEARCH SERVICES IN ACCOUNT;

SELECT USAGE_DATE, SERVICE_TYPE, SUM(CREDITS_BILLED) AS CREDITS_BILLED
FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY
WHERE USAGE_DATE >= DATEADD('day', -19, CURRENT_DATE())
GROUP BY USAGE_DATE, SERVICE_TYPE
ORDER BY USAGE_DATE DESC, CREDITS_BILLED DESC;

-- Currency history can lag by up to 72 hours; it is not a live trial balance.
-- Organization usage access may not be available to every project operator.
SELECT USAGE_DATE, CURRENCY, SERVICE_TYPE,
       SUM(USAGE_IN_CURRENCY) AS USAGE_IN_CURRENCY
FROM SNOWFLAKE.ORGANIZATION_USAGE.USAGE_IN_CURRENCY_DAILY
WHERE USAGE_DATE >= DATEADD('day', -19, CURRENT_DATE())
  AND ACCOUNT_NAME = CURRENT_ACCOUNT_NAME()
GROUP BY USAGE_DATE, CURRENCY, SERVICE_TYPE
ORDER BY USAGE_DATE DESC, USAGE_IN_CURRENCY DESC;
